export function systemFor(mode, role) {
  if (role === "research") return `${COMMON}\nあなたの役割は「調査役」です。Web 検索で最新の事実を集め、出典付きで短くまとめます。意見や売買の提案はしません。`;
  return `${COMMON}\n${ROLE[mode][role === "ideaA" || role === "ideaB" ? "idea" : role]}`;
}

