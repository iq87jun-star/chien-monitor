// 表記ゆれをそろえる(全角数字・英字を半角に、中黒を消す)。空白は区切りとして「|」にする
export const norm = (s) =>
  s
    .normalize("NFKC")
    .replace(/[・･]/g, "")
    .replace(/\s+/g, "|")
    .replace(/c(?=[0-6])/g, "C")
    .replace(/e(?=[0-6])/g, "E");
